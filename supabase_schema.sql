-- 1. TABELA DE TRANSAÇÕES FINANCEIRAS
CREATE TABLE IF NOT EXISTS public.transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data DATE NOT NULL DEFAULT CURRENT_DATE,
    ciclo TEXT NOT NULL,
    tipo TEXT NOT NULL CHECK (tipo IN ('Receita', 'Despesa Fixa', 'Despesa Variável')),
    categoria TEXT NOT NULL,
    descricao TEXT NOT NULL,
    valor NUMERIC(12, 2) NOT NULL,
    responsavel TEXT NOT NULL,
    forma_pagamento TEXT NOT NULL DEFAULT 'PIX',
    origem_comprovante TEXT NOT NULL DEFAULT 'com_nota' CHECK (origem_comprovante IN ('com_nota', 'sem_nota')),
    cartao_nome TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Índices de consulta rápida
CREATE INDEX IF NOT EXISTS idx_transactions_ciclo ON public.transactions(ciclo);
CREATE INDEX IF NOT EXISTS idx_transactions_data ON public.transactions(data);
CREATE INDEX IF NOT EXISTS idx_transactions_categoria ON public.transactions(categoria);
CREATE INDEX IF NOT EXISTS idx_transactions_responsavel ON public.transactions(responsavel);

-- 2. TABELA DE CARTÕES DE CRÉDITO E LIMITES
CREATE TABLE IF NOT EXISTS public.credit_cards (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    titular TEXT NOT NULL,
    final_4 TEXT,
    limite NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    cor TEXT DEFAULT 'purple',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. TABELA DE CICLOS MENSAIS
CREATE TABLE IF NOT EXISTS public.cycles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL UNIQUE,
    data_inicio DATE,
    data_fim DATE,
    salario_planejado NUMERIC(12, 2) DEFAULT 5560.00,
    is_ativo BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. TABELA DE COMPRAS PARCELADAS
CREATE TABLE IF NOT EXISTS public.installments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao TEXT NOT NULL,
    valor_parcela NUMERIC(12, 2) NOT NULL,
    total_parcelas INT NOT NULL,
    parcela_atual INT NOT NULL DEFAULT 1,
    valor_total NUMERIC(12, 2) NOT NULL,
    cartao TEXT,
    ciclo_inicio TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 5. TABELA DE COFRINHOS E RESERVAS
CREATE TABLE IF NOT EXISTS public.piggies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    meta NUMERIC(12, 2) NOT NULL,
    saldo_atual NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    cor TEXT DEFAULT 'blue',
    icone TEXT DEFAULT 'piggy-bank',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 6. TABELA DE ORÇAMENTO DE ALIMENTAÇÃO / SUPERMERCADO
CREATE TABLE IF NOT EXISTS public.food_budget (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ciclo TEXT NOT NULL UNIQUE,
    meta_mensal NUMERIC(12, 2) NOT NULL DEFAULT 1500.00,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 7. TABELA DE HISTÓRICO DE PREÇOS (COMPARADOR DE MERCADO)
CREATE TABLE IF NOT EXISTS public.price_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto TEXT NOT NULL,
    estabelecimento TEXT NOT NULL,
    data DATE NOT NULL DEFAULT CURRENT_DATE,
    preco NUMERIC(12, 2) NOT NULL,
    preco_anterior NUMERIC(12, 2),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- HABILITAR REALTIME (SINCRONIZAÇÃO EM TEMPO REAL)
DO $$
BEGIN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.transactions;
    ALTER PUBLICATION supabase_realtime ADD TABLE public.credit_cards;
    ALTER PUBLICATION supabase_realtime ADD TABLE public.installments;
    ALTER PUBLICATION supabase_realtime ADD TABLE public.piggies;
    ALTER PUBLICATION supabase_realtime ADD TABLE public.price_history;
EXCEPTION WHEN OTHERS THEN
END $$;

-- POLÍTICAS DE ACESSO (RLS)
