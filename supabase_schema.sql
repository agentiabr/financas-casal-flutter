ALTER TABLE public.installments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.piggies ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.food_budget ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.price_history ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Acesso Total Transactions" ON public.transactions FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Acesso Total CreditCards" ON public.credit_cards FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Acesso Total Cycles" ON public.cycles FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Acesso Total Installments" ON public.installments FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Acesso Total Piggies" ON public.piggies FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Acesso Total FoodBudget" ON public.food_budget FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Acesso Total PriceHistory" ON public.price_history FOR ALL USING (true) WITH CHECK (true);

