-- Este script:
-- 1. Cria as tabelas de Família (households, membros, chat e compras compartilhadas).
-- 2. Adiciona colunas de família sem quebrar as 215 transações existentes.
-- 3. Limpa qualquer chave de API do snapshot legado (id: 999999).
-- 4. Cria a função que atribui os 215 lançamentos e cartões à família assim que fizerem login.
-- 5. Mantém o aplicativo atual funcionando normalmente sem bloqueios inesperados.
-- ============================================================================

begin;

create extension if not exists pgcrypto;

-- 1. Tabelas de Família e Membros
create table if not exists public.households (
  id bigint generated by default as identity primary key,
  nome_familia text not null default 'Família Rodrigo & Márcia',
  plano text not null default 'familia',
  max_membros integer not null default 6,
  finance_mode text not null default 'shared' check (finance_mode in ('shared','separate')),
  created_at timestamptz not null default now()
);

create table if not exists public.household_members (
  id bigint generated by default as identity primary key,
  household_id bigint not null references public.households(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  nome text not null,
  email text not null,
  papel text not null default 'admin' check (papel in ('admin','membro')),
  financial_profile text not null default 'adult' check (financial_profile in ('adult','child','dependent','other')),
  finance_visibility text not null default 'shared' check (finance_visibility in ('shared','private')),
  created_at timestamptz not null default now(),
  constraint household_members_household_user_key unique (household_id, user_id)
);

create table if not exists public.household_invites (
  id uuid primary key default gen_random_uuid(),
  household_id bigint not null references public.households(id) on delete cascade,
  code_digest bytea not null unique,
  created_by uuid not null default auth.uid() references auth.users(id),
  expires_at timestamptz not null,
  used_by uuid references auth.users(id),
  used_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.household_app_snapshots (
  household_id bigint not null references public.households(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  payload jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  primary key(household_id, user_id)
);

-- 2. Chat da Família e Lista de Compras Compartilhada
create table if not exists public.family_conversations (
  id uuid primary key default gen_random_uuid(),
  household_id bigint not null references public.households(id) on delete cascade,
  tipo text not null default 'geral' check (tipo in ('geral','compras','direto')),
  titulo text not null default 'Chat da Família',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.family_chat_messages (
  id uuid primary key default gen_random_uuid(),
  conversation_id uuid not null references public.family_conversations(id) on delete cascade,
  sender_user_id uuid not null references auth.users(id) on delete cascade,
  sender_nome text not null,
  conteudo text not null,
  anexos jsonb default '[]'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.shopping_lists (
  id uuid primary key default gen_random_uuid(),
  household_id bigint not null references public.households(id) on delete cascade,
  nome text not null default 'Lista de Compras',
  status text not null default 'aberta' check (status in ('aberta','concluida','cancelada')),
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.shopping_list_items (
  id text primary key,
  list_id uuid not null references public.shopping_lists(id) on delete cascade,
  nome text not null,
  categoria text default 'Supermercado',
  quantidade numeric(10,3) not null default 1,
  preco_estimado numeric(10,2) default 0,
  comprado boolean not null default false,
  comprado_por uuid references auth.users(id),
  created_at timestamptz not null default now()
);

-- 3. Adicionar Colunas de Família nas Tabelas Existentes (Preservando 100% dos dados)
alter table public.transactions add column if not exists household_id bigint references public.households(id) on delete cascade;
alter table public.transactions add column if not exists user_id uuid references auth.users(id);

alter table public.credit_cards add column if not exists household_id bigint references public.households(id) on delete cascade;
alter table public.credit_cards add column if not exists user_id uuid references auth.users(id);

alter table public.piggies add column if not exists household_id bigint references public.households(id) on delete cascade;
alter table public.piggies add column if not exists user_id uuid references auth.users(id);

-- 4. Limpeza da Chave Antiga no Registro de Snapshot Legado
update public.transactions
set descricao = (descricao::jsonb - 'geminiKey')::text
where id = 999999
  and jsonb_typeof(descricao::jsonb) = 'object'
  and descricao::jsonb ? 'geminiKey';

-- 5. Função de Segurança Auxiliar
create or replace function public.is_household_member(p_household_id bigint)
returns boolean language sql stable security definer set search_path = public, pg_temp as $$
  select exists(
    select 1 from public.household_members hm
    where hm.household_id = p_household_id and hm.user_id = auth.uid()
  );
$$;

-- 6. Função para Criar Família e Reivindicar Todos os Lançamentos Históricos
create or replace function public.create_household_and_claim_history(p_nome_familia text default 'Família Rodrigo & Márcia')
returns bigint language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_household_id bigint;
  v_email text;
  v_name text := left(trim(coalesce(p_nome_familia, 'Família Rodrigo & Márcia')), 100);
begin
  if auth.uid() is null then
    raise exception 'Você precisa estar autenticado para criar a família.';
  end if;

  select email into v_email from auth.users where id = auth.uid();

  -- Se o usuário já tiver família, retorna a existente
  select household_id into v_household_id from public.household_members where user_id = auth.uid() limit 1;
  
  if v_household_id is null then
    insert into public.households(nome_familia, plano, max_membros, finance_mode)
      values(v_name, 'familia', 6, 'shared')
      returning id into v_household_id;

    insert into public.household_members(household_id, user_id, nome, email, papel, financial_profile, finance_visibility)
      values(v_household_id, auth.uid(), v_name, coalesce(v_email, ''), 'admin', 'adult', 'shared');
  end if;

  -- Associa automaticamente todas as 215 transações legadas sem família à nova família
  update public.transactions
  set household_id = v_household_id, user_id = auth.uid()
  where id <> 999999
    and ciclo <> '__SYSTEM_BACKUP__'
    and tipo <> '__CLOUD_SNAPSHOT__'
    and (household_id is null or user_id is null);

  -- Associa os cartões e cofrinhos existentes
  update public.credit_cards set household_id = v_household_id, user_id = auth.uid() where household_id is null;
  update public.piggies set household_id = v_household_id, user_id = auth.uid() where household_id is null;

  return v_household_id;
end;
$$;

grant execute on function public.create_household_and_claim_history(text) to authenticated;
grant execute on function public.is_household_member(bigint) to authenticated;

commit;
