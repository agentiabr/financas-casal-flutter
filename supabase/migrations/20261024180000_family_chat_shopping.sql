create or replace function public.complete_shopping_list(p_list_id uuid,p_cycle text,p_payment_method text default 'PIX',p_create_transaction boolean default true)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_list public.shopping_lists%rowtype; v_total numeric(12,2); v_tx_id bigint;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  select * into v_list from public.shopping_lists where id=p_list_id for update;
  if not found or not public.is_household_member(v_list.household_id) then raise exception 'Shopping list not found'; end if;
  if v_list.status='cancelled' then raise exception 'Shopping list was cancelled'; end if;
  select coalesce(round(sum(coalesce(actual_quantity,quantity)*unit_price),2),0) into v_total
    from public.shopping_list_items where list_id=p_list_id and status='purchased' and unit_price is not null;
  if v_list.status='completed' then
    select id into v_tx_id from public.transactions where shopping_list_id=p_list_id;
    return jsonb_build_object('list_id',p_list_id,'total',v_list.actual_total,'transaction_id',v_tx_id,'already_completed',true);
  end if;
  update public.shopping_lists set status='completed',actual_total=v_total,completed_by=auth.uid(),completed_at=now() where id=p_list_id;
  insert into public.price_history(household_id,user_id,produto,estabelecimento,data,preco,shopping_list_item_id)
    select v_list.household_id,auth.uid(),i.name,coalesce(v_list.store_name,'Supermercado'),current_date,i.unit_price,i.id
    from public.shopping_list_items i where i.list_id=p_list_id and i.status='purchased' and i.unit_price is not null
    on conflict (shopping_list_item_id) where shopping_list_item_id is not null do nothing;
  if p_create_transaction and v_total>0 then
    insert into public.transactions(household_id,user_id,shopping_list_id,data,ciclo,tipo,categoria,descricao,valor,responsavel,forma_pagamento,origem_comprovante)
    values(v_list.household_id,auth.uid(),p_list_id,current_date,coalesce(nullif(trim(p_cycle),''),to_char(current_date,'MM/YYYY')),
      'Despesa Variável','Alimentação','Compras de supermercado ('||p_list_id::text||')',v_total,
      coalesce((select nome from public.household_members where household_id=v_list.household_id and user_id=auth.uid()),'Membro'),
      coalesce(nullif(trim(p_payment_method),''),'PIX'),'sem_nota')
    on conflict (shopping_list_id) where shopping_list_id is not null do nothing
    returning id into v_tx_id;
    if v_tx_id is null then select id into v_tx_id from public.transactions where shopping_list_id=p_list_id; end if;
  end if;
  return jsonb_build_object('list_id',p_list_id,'total',v_total,'transaction_id',v_tx_id,'already_completed',false);
end; $$;
create or replace function public.record_shopping_receipt(
  p_list_id uuid,p_total numeric,p_access_key text,p_store_name text,p_purchased_at date,
  p_items jsonb,p_cycle text,p_payment_method text default 'PIX'
) returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_list public.shopping_lists%rowtype; v_receipt_id uuid; v_tx_id bigint; v_item jsonb; v_name text; v_qty numeric; v_price numeric; v_line numeric; v_unit text; v_code text;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  if p_total is null or p_total<=0 then raise exception 'Receipt total must be positive'; end if;
  select * into v_list from public.shopping_lists where id=p_list_id for update;
  if not found or not public.is_household_member(v_list.household_id) then raise exception 'Shopping list not found'; end if;
  if v_list.status='cancelled' then raise exception 'Shopping list was cancelled'; end if;
  if v_list.status<>'completed' then perform public.complete_shopping_list(p_list_id,p_cycle,p_payment_method,false); end if;
  insert into public.shopping_receipts(list_id,household_id,scanned_by,access_key,store_name,purchased_at,total)
  values(p_list_id,v_list.household_id,auth.uid(),nullif(trim(coalesce(p_access_key,'')),''),nullif(trim(coalesce(p_store_name,'')),''),coalesce(p_purchased_at,current_date),p_total)
  on conflict(list_id) do update set scanned_by=excluded.scanned_by,access_key=coalesce(excluded.access_key,shopping_receipts.access_key),store_name=coalesce(excluded.store_name,shopping_receipts.store_name),purchased_at=excluded.purchased_at,total=excluded.total
  returning id into v_receipt_id;
  delete from public.shopping_receipt_items where receipt_id=v_receipt_id;
  for v_item in select value from jsonb_array_elements(coalesce(p_items,'[]'::jsonb)) loop
    v_name:=left(coalesce(nullif(trim(v_item->>'name'),''),nullif(trim(v_item->>'produto'),''),'Produto'),200);
    v_qty:=greatest(coalesce(nullif(coalesce(v_item->>'quantity',v_item->>'qtd'),'')::numeric,1),0.001);
    v_price:=greatest(coalesce(nullif(coalesce(v_item->>'unit_price',v_item->>'preco'),'')::numeric,0),0);
    v_line:=greatest(coalesce(nullif(coalesce(v_item->>'line_total',v_item->>'total'),'')::numeric,v_qty*v_price),0);
    v_unit:=left(coalesce(nullif(trim(coalesce(v_item->>'unit',v_item->>'unidade')),''),'UN'),12);
    v_code:=left(coalesce(nullif(trim(coalesce(v_item->>'product_code',v_item->>'codigo')),''),''),64);
    insert into public.shopping_receipt_items(receipt_id,household_id,product_name,quantity,unit,unit_price,line_total,product_code)
    values(v_receipt_id,v_list.household_id,v_name,v_qty,v_unit,v_price,v_line,nullif(v_code,''));
    if v_price>0 then
      insert into public.price_history(household_id,user_id,produto,estabelecimento,data,preco,shopping_list_item_id)
      values(v_list.household_id,auth.uid(),v_name,coalesce(nullif(p_store_name,''),v_list.store_name,'Supermercado'),coalesce(p_purchased_at,current_date),v_price,
        (select i.id from public.shopping_list_items i where i.list_id=p_list_id and lower(i.name)=lower(v_name) order by i.created_at limit 1))
      on conflict(shopping_list_item_id) where shopping_list_item_id is not null do update set preco=excluded.preco,estabelecimento=excluded.estabelecimento,data=excluded.data;
    end if;
  end loop;
  update public.shopping_lists set actual_total=p_total,store_name=coalesce(nullif(p_store_name,''),store_name) where id=p_list_id;
  insert into public.transactions(household_id,user_id,shopping_list_id,data,ciclo,tipo,categoria,descricao,valor,responsavel,forma_pagamento,origem_comprovante)
  values(v_list.household_id,auth.uid(),p_list_id,coalesce(p_purchased_at,current_date),coalesce(nullif(trim(p_cycle),''),to_char(current_date,'MM/YYYY')),
    'Despesa Variável','Alimentação','Compra com NFC-e - '||coalesce(nullif(p_store_name,''),v_list.store_name,'Supermercado'),p_total,
    coalesce((select nome from public.household_members where household_id=v_list.household_id and user_id=auth.uid()),'Membro'),coalesce(nullif(trim(p_payment_method),''),'PIX'),'com_nota')
  on conflict(shopping_list_id) where shopping_list_id is not null do update set valor=excluded.valor,data=excluded.data,descricao=excluded.descricao,forma_pagamento=excluded.forma_pagamento,origem_comprovante='com_nota'
  returning id into v_tx_id;
  if v_tx_id is null then select id into v_tx_id from public.transactions where shopping_list_id=p_list_id; end if;
  return jsonb_build_object('receipt_id',v_receipt_id,'list_id',p_list_id,'total',p_total,'transaction_id',v_tx_id,'item_count',jsonb_array_length(coalesce(p_items,'[]'::jsonb)));
end; $$;
