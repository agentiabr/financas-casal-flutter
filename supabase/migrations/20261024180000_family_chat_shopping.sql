create or replace function public.create_household_for_current_user(p_name text, p_finance_mode text default 'shared')
returns bigint language plpgsql security definer set search_path=public,pg_temp as $$
declare v_household_id bigint; v_email text; v_name text:=left(trim(coalesce(p_name,'')),100);
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  if v_name='' then raise exception 'Household name is required'; end if;
  if exists(select 1 from public.household_members where user_id=auth.uid()) then
    raise exception 'User already belongs to a household';
  end if;
  select email into v_email from auth.users where id=auth.uid();
  insert into public.households(nome_familia,plano,max_membros,finance_mode)
    values(v_name,'familia',6,case when p_finance_mode='separate' then 'separate' else 'shared' end)
    returning id into v_household_id;
  insert into public.household_members(household_id,user_id,nome,email,papel,financial_profile,finance_visibility)
    values(v_household_id,auth.uid(),v_name,coalesce(v_email,''),'admin','adult','shared');
  return v_household_id;
end; $$;
revoke all on function public.create_household_for_current_user(text,text) from public,anon;
grant execute on function public.create_household_for_current_user(text,text) to authenticated;
create or replace function public.create_household_invite(p_household_id bigint,p_expires_in_days integer default 7)
returns text language plpgsql security definer set search_path=public,pg_temp as $$
declare v_code text:=upper(encode(gen_random_bytes(8),'hex')); v_count integer; v_max integer;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  if not exists(select 1 from public.household_members where household_id=p_household_id and user_id=auth.uid() and papel='admin') then
    raise exception 'Only a household admin can invite members';
  end if;
  select count(*) into v_count from public.household_members where household_id=p_household_id;
  select max_membros into v_max from public.households where id=p_household_id;
  if v_count>=least(coalesce(v_max,6),6) then raise exception 'Household member limit reached'; end if;
  insert into public.household_invites(household_id,code_digest,expires_at)
  values(p_household_id,digest(v_code,'sha256'),now()+make_interval(days=>greatest(1,least(p_expires_in_days,30))));
  return v_code;
end; $$;

create or replace function public.join_household_with_invite(p_code text,p_nome text,p_financial_profile text default 'adult',p_finance_visibility text default 'shared')
returns bigint language plpgsql security definer set search_path=public,pg_temp as $$
declare v_invite public.household_invites%rowtype; v_email text; v_count integer; v_max integer;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  select * into v_invite from public.household_invites
    where code_digest=digest(upper(trim(p_code)),'sha256') and used_at is null and expires_at>now() for update;
  if not found then raise exception 'Invite code is invalid or expired'; end if;
  select count(*) into v_count from public.household_members where household_id=v_invite.household_id;
  select max_membros into v_max from public.households where id=v_invite.household_id;
  if v_count>=least(coalesce(v_max,6),6) then raise exception 'Household member limit reached'; end if;
  if exists(select 1 from public.household_members where household_id=v_invite.household_id and user_id=auth.uid()) then raise exception 'Already a household member'; end if;
  select email into v_email from auth.users where id=auth.uid();
  insert into public.household_members(household_id,user_id,nome,email,papel,financial_profile,finance_visibility)
  values(v_invite.household_id,auth.uid(),left(trim(p_nome),100),coalesce(v_email,''),'membro',
    case when p_financial_profile in ('adult','child','dependent','other') then p_financial_profile else 'adult' end,
    case when p_finance_visibility in ('shared','private') then p_finance_visibility else 'shared' end);
  update public.household_invites set used_by=auth.uid(),used_at=now() where id=v_invite.id;
  return v_invite.household_id;
end; $$;
