create or replace function public.prune_family_chat_messages(p_conversation_id uuid,p_keep_count integer default 100)
returns integer language plpgsql security definer set search_path=public,pg_temp as $$
declare v_household_id bigint; v_deleted integer;
begin
  select household_id into v_household_id from public.family_conversations where id=p_conversation_id;
  if v_household_id is null or not public.is_household_member(v_household_id) then raise exception 'Conversation not found'; end if;
  with obsolete as (
    select id from public.family_chat_messages where conversation_id=p_conversation_id
    order by created_at desc,id desc offset greatest(1,least(p_keep_count,100))
  )
  delete from public.family_chat_messages m using obsolete o where m.id=o.id;
  get diagnostics v_deleted=row_count;
  return v_deleted;
end; $$;
