-- Finance visibility: shared households can see member transactions; separate households
-- expose each member's rows only when that owner opted into sharing. Writes stay owner-only.
create or replace function public.can_read_household_transaction(p_household_id bigint,p_owner_id uuid)
returns boolean language sql stable security definer set search_path=public,pg_temp as $$
  select exists (
    select 1
    from public.households h
    join public.household_members viewer on viewer.household_id=h.id and viewer.user_id=auth.uid()
    where h.id=p_household_id and (
      h.finance_mode='shared'
      or (p_owner_id=auth.uid())
      or (p_owner_id is not null and exists (
        select 1 from public.household_members owner
        where owner.household_id=h.id and owner.user_id=p_owner_id and owner.finance_visibility='shared'
      ))
      -- Legacy household rows without an owner remain available to the admin only in separate mode.
      or (p_owner_id is null and viewer.papel='admin')
    )
  );
$$;revoke all on function public.can_read_household_transaction(bigint,uuid) from public,anon;
grant execute on function public.can_read_household_transaction(bigint,uuid) to authenticated;

