-- Execute no SQL Editor do Supabase (projeto de PRODUÇÃO) depois de fazer backup.
--
-- O que entrega:
--  1) public.delete_my_account()   -> exclusão definitiva da conta (LGPD art. 18, VI)
--  2) public.user_roles + is_master() -> papel de administrador validado NO SERVIDOR
--  3) public.audit_logs            -> trilha de auditoria append-only (sem UPDATE/DELETE)
--  4) public.legal_consents        -> registro de consentimentos (versão/data)
--
-- Nota: o app já chama delete_my_account() (ação nativa 'delete_account').
-- audit_logs e legal_consents ficam prontos para o app sincronizar; hoje o app
-- grava esses registros localmente e no aparelho do usuário.
-- ==============================================================================

-- 1) Exclusão de conta -----------------------------------------------------------
create or replace function public.delete_my_account()
returns void
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
  v_uid uuid := auth.uid();
  r record;
begin
  if v_uid is null then
    raise exception 'Não autenticado';
  end if;

  -- Para toda FK de tabelas public -> auth.users SEM cascade/set null:
  -- remove as linhas do usuário (coluna NOT NULL) ou anula a referência (coluna nula).
  for r in
    select n.nspname as sch, c.relname as tbl, a.attname as col, a.attnotnull as notnull
    from pg_constraint con
    join pg_class c on c.oid = con.conrelid
    join pg_namespace n on n.oid = c.relnamespace
    join pg_attribute a on a.attrelid = con.conrelid and a.attnum = any (con.conkey)
    where con.contype = 'f'
      and con.confrelid = 'auth.users'::regclass
      and n.nspname = 'public'
      and con.confdeltype in ('a', 'r')
  loop
    if r.notnull then
      execute format('delete from %I.%I where %I = $1', r.sch, r.tbl, r.col) using v_uid;
    else
      execute format('update %I.%I set %I = null where %I = $1', r.sch, r.tbl, r.col, r.col) using v_uid;
    end if;
  end loop;

  delete from auth.users where id = v_uid;  -- FKs com ON DELETE CASCADE limpam o restante
end;
$$;

revoke all on function public.delete_my_account() from public, anon;
grant execute on function public.delete_my_account() to authenticated;

-- 2) Papéis (administrador validado no servidor) --------------------------------
create table if not exists public.user_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'member' check (role in ('master', 'member')),
  created_at timestamptz not null default now()
);
alter table public.user_roles enable row level security;

drop policy if exists "user_roles_select_own" on public.user_roles;
create policy "user_roles_select_own" on public.user_roles
  for select to authenticated using (user_id = auth.uid());
-- Sem policies de INSERT/UPDATE/DELETE: clientes não conseguem se promover.
-- Para definir o administrador, rode manualmente (uma vez):
--   insert into public.user_roles (user_id, role)
--   select id, 'master' from auth.users where email = 'rodrigocardosocn@gmail.com'
--   on conflict (user_id) do update set role = 'master';

create or replace function public.is_master()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (select 1 from public.user_roles where user_id = auth.uid() and role = 'master');
$$;
revoke all on function public.is_master() from public, anon;
grant execute on function public.is_master() to authenticated;

-- 3) Auditoria append-only -------------------------------------------------------
create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null default auth.uid(),
  event text not null check (char_length(event) <= 60),
  meta jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
alter table public.audit_logs enable row level security;

drop policy if exists "audit_logs_insert_own" on public.audit_logs;
create policy "audit_logs_insert_own" on public.audit_logs
  for insert to authenticated with check (user_id = auth.uid());
drop policy if exists "audit_logs_select_own" on public.audit_logs;
create policy "audit_logs_select_own" on public.audit_logs
  for select to authenticated using (user_id = auth.uid() or public.is_master());
-- Sem UPDATE/DELETE: trilha imutável para clientes.
create index if not exists audit_logs_user_created_idx on public.audit_logs (user_id, created_at desc);

-- 4) Consentimentos --------------------------------------------------------------
create table if not exists public.legal_consents (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade default auth.uid(),
  kind text not null check (kind in ('terms', 'privacy', 'kids', 'health', 'ai')),
  version text not null,
  granted boolean not null default true,
  created_at timestamptz not null default now()
);
alter table public.legal_consents enable row level security;

drop policy if exists "legal_consents_own" on public.legal_consents;
create policy "legal_consents_own" on public.legal_consents
  for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
create index if not exists legal_consents_user_idx on public.legal_consents (user_id, kind, created_at desc);
