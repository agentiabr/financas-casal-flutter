-- ==============================================================================
-- SCHEMA SUPABASE SEGURO COM ROW LEVEL SECURITY (RLS) MULTI-TENANT POR FAMÍLIA
-- CtrlPig • Controle Financeiro Inteligente
-- ==============================================================================
-- Este script resolve a vulnerabilidade crítica apontada pelo relatório do CODEX:
-- Anteriormente, as políticas utilizavam 'USING (true) WITH CHECK (true)',
-- o que permitia acesso irrestrito a qualquer portador da chave anônima.
-- 
-- Este schema estabelece:
-- 1. Isolamento completo por conta (auth.users) e família (households/household_members).
-- 2. Cada transação, cartão, cofrinho e histórico de preços pertence a um 'household_id' e/ou 'user_id'.
-- 3. Apenas usuários autenticados pertencentes ao mesmo grupo familiar podem visualizar e editar os dados.
-- ==============================================================================

-- 1. EXTENSÕES NECESSÁRIAS
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 2. TABELA DE FAMÍLIAS / HOUSEHOLDS
CREATE TABLE IF NOT EXISTS public.households (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_familia TEXT NOT NULL DEFAULT 'Família',
    plano TEXT NOT NULL DEFAULT 'casal' CHECK (plano IN ('solteiro', 'casal', 'familia')),
    max_membros INT NOT NULL DEFAULT 2,
    preco_mensal NUMERIC(10, 2) NOT NULL DEFAULT 29.90,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. MEMBROS DA FAMÍLIA VINCULADOS AO AUTH.USERS DO SUPABASE
CREATE TABLE IF NOT EXISTS public.household_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT NOT NULL REFERENCES public.households(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    nome TEXT NOT NULL,
    email TEXT NOT NULL,
    papel TEXT NOT NULL DEFAULT 'membro' CHECK (papel IN ('admin', 'membro')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT unique_user_household UNIQUE (household_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_members_user ON public.household_members(user_id);
CREATE INDEX IF NOT EXISTS idx_members_household ON public.household_members(household_id);

-- 4. FUNÇÃO AUXILIAR DE SEGURANÇA (STABLE / DEFINER)
-- Retorna os IDs dos grupos familiares aos quais o usuário autenticado pertence
CREATE OR REPLACE FUNCTION public.get_my_household_ids()
RETURNS SETOF BIGINT
LANGUAGE sql
SECURITY DEFINER
STABLE
AS $$
    SELECT household_id 
    FROM public.household_members 
    WHERE user_id = auth.uid();
$$;

-- 5. TABELA DE TRANSAÇÕES FINANCEIRAS
CREATE TABLE IF NOT EXISTS public.transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT REFERENCES public.households(id) ON DELETE CASCADE,
    user_id UUID REFERENCES auth.users(id) DEFAULT auth.uid(),
    data DATE NOT NULL DEFAULT CURRENT_DATE,
    ciclo TEXT NOT NULL,
    tipo TEXT NOT NULL CHECK (tipo IN ('Receita', 'Despesa Fixa', 'Despesa Variável')),
    categoria TEXT NOT NULL,
    descricao TEXT NOT NULL,
    valor NUMERIC(12, 2) NOT NULL,
    responsavel TEXT NOT NULL,
    forma_pagamento TEXT NOT NULL DEFAULT 'PIX',
    origem_comprovante TEXT NOT NULL DEFAULT 'com_nota' CHECK (origem_comprovante IN ('com_nota', 'sem_nota')),
    cartao_nome TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_transactions_household ON public.transactions(household_id);
CREATE INDEX IF NOT EXISTS idx_transactions_user ON public.transactions(user_id);
CREATE INDEX IF NOT EXISTS idx_transactions_ciclo ON public.transactions(ciclo);
CREATE INDEX IF NOT EXISTS idx_transactions_data ON public.transactions(data);

-- 6. TABELA DE CARTÕES DE CRÉDITO
CREATE TABLE IF NOT EXISTS public.credit_cards (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT REFERENCES public.households(id) ON DELETE CASCADE,
    user_id UUID REFERENCES auth.users(id) DEFAULT auth.uid(),
    nome TEXT NOT NULL,
    titular TEXT NOT NULL,
    final_4 TEXT,
    limite NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    cor TEXT DEFAULT 'purple',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_cards_household ON public.credit_cards(household_id);

-- 7. TABELA DE COFRINHOS E RESERVAS
CREATE TABLE IF NOT EXISTS public.piggies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT REFERENCES public.households(id) ON DELETE CASCADE,
    user_id UUID REFERENCES auth.users(id) DEFAULT auth.uid(),
    nome TEXT NOT NULL,
    meta NUMERIC(12, 2) NOT NULL,
    saldo_atual NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    cor TEXT DEFAULT 'blue',
    icone TEXT DEFAULT 'piggy-bank',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_piggies_household ON public.piggies(household_id);

-- 8. TABELA DE COMPRAS PARCELADAS
CREATE TABLE IF NOT EXISTS public.installments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT REFERENCES public.households(id) ON DELETE CASCADE,
    user_id UUID REFERENCES auth.users(id) DEFAULT auth.uid(),
    descricao TEXT NOT NULL,
    valor_parcela NUMERIC(12, 2) NOT NULL,
    total_parcelas INT NOT NULL,
    parcela_atual INT NOT NULL DEFAULT 1,
    valor_total NUMERIC(12, 2) NOT NULL,
    cartao TEXT,
    ciclo_inicio TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 9. TABELA DE ORÇAMENTO DE ALIMENTAÇÃO / SUPERMERCADO
CREATE TABLE IF NOT EXISTS public.food_budget (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT REFERENCES public.households(id) ON DELETE CASCADE,
    user_id UUID REFERENCES auth.users(id) DEFAULT auth.uid(),
    ciclo TEXT NOT NULL,
    meta_mensal NUMERIC(12, 2) NOT NULL DEFAULT 1500.00,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT unique_budget_cycle_household UNIQUE (household_id, ciclo)
);

-- 10. TABELA DE HISTÓRICO DE PREÇOS (COMPARADOR DE MERCADOS)
CREATE TABLE IF NOT EXISTS public.price_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT REFERENCES public.households(id) ON DELETE CASCADE,
    user_id UUID REFERENCES auth.users(id) DEFAULT auth.uid(),
    produto TEXT NOT NULL,
    estabelecimento TEXT NOT NULL,
    data DATE NOT NULL DEFAULT CURRENT_DATE,
    preco NUMERIC(12, 2) NOT NULL,
    preco_anterior NUMERIC(12, 2),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 11. TABELA DE MENSAGENS DO CHAT FAMILIAR
CREATE TABLE IF NOT EXISTS public.chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT REFERENCES public.households(id) ON DELETE CASCADE,
    user_id UUID REFERENCES auth.users(id) DEFAULT auth.uid(),
    sender_name TEXT NOT NULL,
    text TEXT NOT NULL,
    image_url TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_chat_household ON public.chat_messages(household_id);

-- ==============================================================================
-- 12. HABILITAR ROW LEVEL SECURITY (RLS) RIGOROSO EM TODAS AS TABELAS
-- ==============================================================================
ALTER TABLE public.households ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.household_members ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.transactions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.credit_cards ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.piggies ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.installments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.food_budget ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.price_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.chat_messages ENABLE ROW LEVEL SECURITY;

-- ==============================================================================
-- 13. POLÍTICAS DE ACESSO RESTRITAS E SEGURAS
-- ==============================================================================

-- HOUSEHOLDS: O usuário só vê o grupo familiar do qual é membro
DROP POLICY IF EXISTS "Household Member View" ON public.households;
CREATE POLICY "Household Member View" ON public.households
    FOR SELECT TO authenticated
    USING (id IN (SELECT public.get_my_household_ids()));

-- HOUSEHOLD MEMBERS: Usuários só visualizam membros da sua própria família
DROP POLICY IF EXISTS "Household Members View" ON public.household_members;
CREATE POLICY "Household Members View" ON public.household_members
    FOR ALL TO authenticated
    USING (household_id IN (SELECT public.get_my_household_ids()))
    WITH CHECK (household_id IN (SELECT public.get_my_household_ids()));

-- TRANSACTIONS: Somente usuários do mesmo household ou dono direto (user_id)
DROP POLICY IF EXISTS "Transactions Household Isolation" ON public.transactions;
CREATE POLICY "Transactions Household Isolation" ON public.transactions
    FOR ALL TO authenticated
    USING (
        (household_id IS NOT NULL AND household_id IN (SELECT public.get_my_household_ids()))
        OR (user_id IS NOT NULL AND user_id = auth.uid())
    )
    WITH CHECK (
        (household_id IS NOT NULL AND household_id IN (SELECT public.get_my_household_ids()))
        OR (user_id IS NOT NULL AND user_id = auth.uid())
    );

